type IconProps = {
  name: string;
  className?: string;
  size?: number;
};

export default function Icon({ name, className, size = 18 }: IconProps) {
  const Component = ICONS[name];
  if (!Component) return null;
  return (
    <Component
      className={`icon${className ? ` ${className}` : ''}`}
      size={size}
      strokeWidth={1.5}
      aria-hidden="true"
    />
  );
}
